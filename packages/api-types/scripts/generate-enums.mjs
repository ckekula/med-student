// packages/api-types/scripts/generate-enums.mjs
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const [, , inputArg, outputArg] = process.argv;
const SCHEMA_URL = inputArg ?? process.env.BACKEND_SCHEMA_URL ?? "http://localhost:8000/openapi.json";
const OUTPUT_PATH = resolve(outputArg ?? "api-enums.generated.ts");

const toScreamingSnakeCase = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();

async function loadSchema(url) {
  let res;
  try {
    res = await fetch(url);
  } catch (error) {
    console.error(`Could not reach ${url}.`);
    console.error("Is the backend running? Or pass a schema URL/path as the first argument.");
    throw error;
  }
  if (!res.ok) {
    throw new Error(`${url} responded ${res.status} ${res.statusText}`);
  }
  return res.json();
}

function findStringEnums(openapiDocument) {
  const schemas = openapiDocument?.components?.schemas ?? {};
  const enums = [];
  for (const [name, schema] of Object.entries(schemas)) {
    if (schema?.type === "string" && Array.isArray(schema.enum) && schema.enum.every((v) => typeof v === "string")) {
      enums.push({ name, values: schema.enum });
    }
  }
  enums.sort((a, b) => a.name.localeCompare(b.name));
  return enums;
}

function renderFile(enums) {
  const lines = [
    "// AUTO-GENERATED by scripts/generate-enums.mjs — do not edit by hand.",
    "// Regenerate with `pnpm api:types` after any backend schema change.",
    "// Source: the same openapi.json used to generate api-schema.d.ts, so these",
    "// values and that file's types can't drift from each other.",
    "",
  ];
  for (const { name, values } of enums) {
    const constName = toScreamingSnakeCase(name);
    const literal = values.map((v) => JSON.stringify(v)).join(", ");
    lines.push(`export const ${constName} = [${literal}] as const;`);
  }
  lines.push("");
  return lines.join("\n");
}

async function main() {
  const schema = await loadSchema(SCHEMA_URL);
  const enums = findStringEnums(schema);

  if (enums.length === 0) {
    console.error(`No string-enum schemas found from ${SCHEMA_URL}.`);
    process.exit(1);
  }

  writeFileSync(OUTPUT_PATH, renderFile(enums));
  console.log(`Wrote ${OUTPUT_PATH} (${enums.length} enum${enums.length === 1 ? "" : "s"}: ${enums.map((e) => e.name).join(", ")}).`);
}

main();