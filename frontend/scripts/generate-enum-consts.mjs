#!/usr/bin/env node
/**
 * Generates runtime `as const` arrays for every string-enum schema in the backend's
 * OpenAPI document — the one piece openapi-typescript deliberately doesn't emit
 * (it only emits types, which don't exist at runtime after compilation).
 *
 * The array values and the generated TypeScript type (from `npm run api:types`,
 * via openapi-typescript) both come from the same openapi.json in the same step,
 * so they can't drift from each other. They can still both go stale relative to
 * the backend if someone forgets to re-run codegen after a backend change — guard
 * against that in CI by re-running codegen and failing the build on a git diff.
 *
 * Usage: node scripts/generate-enum-consts.mjs [path/to/openapi.json] [path/to/output.ts]
 * Defaults match the layout used by `npm run api:types` in this project.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const [, , inputArg, outputArg] = process.argv;
const INPUT_PATH = resolve(inputArg ?? "../backend/openapi.json");
const OUTPUT_PATH = resolve(outputArg ?? "types/api-enums.generated.ts");

const toScreamingSnakeCase = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();

function loadSchema(path) {
  let raw;
  try {
    raw = readFileSync(path, "utf-8");
  } catch (error) {
    console.error(`Could not read ${path}.`);
    console.error("Run the backend's export_openapi.py first, or pass the path as the first argument.");
    throw error;
  }
  return JSON.parse(raw);
}

function findStringEnums(openapiDocument) {
  const schemas = openapiDocument?.components?.schemas ?? {};
  const enums = [];
  for (const [name, schema] of Object.entries(schemas)) {
    if (schema?.type === "string" && Array.isArray(schema.enum) && schema.enum.every((v) => typeof v === "string")) {
      enums.push({ name, values: schema.enum });
    }
  }
  // Stable order regardless of the backend's own key order, so regenerating
  // doesn't produce a diff-only-in-order commit.
  enums.sort((a, b) => a.name.localeCompare(b.name));
  return enums;
}

function renderFile(enums) {
  const lines = [
    "// AUTO-GENERATED by scripts/generate-enum-consts.mjs — do not edit by hand.",
    "// Regenerate with `npm run api:types` after any backend schema change.",
    "// Source: the same openapi.json used to generate api-schema.d.ts, so these",
    "// values and that file's types can't drift from each other.",
    "",
  ];
  for (const { name, values } of enums) {
    const constName = toScreamingSnakeCase(name);
    const literal = values.map((v) => JSON.stringify(v)).join(", ");
    lines.push(`export const ${constName} = [${literal}] as const;`);
  }
  lines.push("");
  return lines.join("\n");
}

function main() {
  const schema = loadSchema(INPUT_PATH);
  const enums = findStringEnums(schema);

  if (enums.length === 0) {
    console.error(`No string-enum schemas found in ${INPUT_PATH}. Check the input file is a valid OpenAPI document.`);
    process.exit(1);
  }

  writeFileSync(OUTPUT_PATH, renderFile(enums));
  console.log(`Wrote ${OUTPUT_PATH} (${enums.length} enum${enums.length === 1 ? "" : "s"}: ${enums.map((e) => e.name).join(", ")}).`);
}

main();
